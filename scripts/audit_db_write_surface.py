"""Generate the Phase 0 DB write-surface audit.

The audit walks `scripts/brain_index.py deps --table <table>` for every
analyzer-relevant table from the Phase 0 spec and records external write paths
outside brain_index's table dependency index.
"""

from __future__ import annotations

import argparse
from datetime import datetime, timezone
from pathlib import Path
import subprocess


TABLES: list[tuple[str, str]] = [
    ("low_buy_trades", "legacy"),
    ("wallet_analysis_queue", "legacy"),
    ("discovery_events", "legacy"),
    ("candidate_users", "legacy"),
    ("user_analysis", "legacy"),
    ("position_signals", "legacy"),
    ("paper_sell_signals", "legacy"),
    ("flagged_users", "legacy"),
    ("score_history", "legacy"),
    ("signal_history", "legacy"),
    ("wallet_analyzer_intake_queue", "analyzer-owned"),
    ("wallet_analysis_batch", "analyzer-owned"),
    ("wallet_analysis_batch_item", "analyzer-owned"),
    ("analyzer_runs", "analyzer-owned"),
    ("wallet_layer5_decision", "analyzer-owned"),
    ("position_signal_decision", "analyzer-owned"),
    ("tag_market_stats", "analyzer-owned"),
    ("position_market_state", "analyzer-owned"),
    ("wallet_tag_pnl", "support"),
    ("wallet_tag_fit", "support"),
    ("tag_nav_category", "support"),
    ("wallet_profiles", "support"),
    ("wallet_directory", "support"),
    ("followed_wallets", "support"),
    ("followed_wallet_activity", "support"),
    ("market_metadata", "external-feed-derived"),
    ("market_outcomes", "external-feed-derived"),
    ("market_tags", "external-feed-derived"),
]

SKIP_DIRS = {
    ".git",
    ".mypy_cache",
    ".pytest_cache",
    ".ruff_cache",
    ".venv",
    "__pycache__",
    "node_modules",
    "tests",
}

MEMORY_WRITE_TOKENS = (
    "save_finding(",
    "save_memory(",
    ".table('memories')",
    '.table("memories")',
)


def repo_root() -> Path:
    return Path(__file__).resolve().parent.parent


def deps_for(repo: Path, table: str) -> str:
    result = subprocess.run(
        ["python3", "scripts/brain_index.py", "deps", "--table", table],
        cwd=repo,
        capture_output=True,
        text=True,
        timeout=30,
        check=False,
    )
    output = result.stdout.strip()
    if result.returncode != 0 and result.stderr.strip():
        return f"(brain_index exited {result.returncode})\n{result.stderr.strip()}"
    return output or "(no entries from brain_index)"


def iter_python_files(repo: Path) -> list[Path]:
    result = subprocess.run(
        ["git", "ls-files", "-z", "--", "*.py"],
        cwd=repo,
        capture_output=True,
        check=False,
    )
    if result.returncode == 0:
        paths = [repo / item.decode() for item in result.stdout.split(b"\0") if item]
    else:
        paths = repo.rglob("*.py")
    files: list[Path] = []
    for path in paths:
        if any(part in SKIP_DIRS for part in path.relative_to(repo).parts):
            continue
        if path.name == "audit_db_write_surface.py":
            continue
        files.append(path)
    return sorted(files)


def supabase_memory_write_sites(repo: Path) -> list[str]:
    sites: list[str] = []
    for path in iter_python_files(repo):
        rel = path.relative_to(repo)
        try:
            lines = path.read_text(encoding="utf-8").splitlines()
        except UnicodeDecodeError:
            lines = path.read_text(errors="ignore").splitlines()
        for lineno, line in enumerate(lines, start=1):
            if any(token in line for token in MEMORY_WRITE_TOKENS):
                sites.append(f"{rel}:{lineno}: {line.strip()}")
    return sites


def render_audit(repo: Path) -> str:
    lines: list[str] = [
        "---",
        "memory_name: audit/db-write-surface-2026-04-30",
        "memory_type: reference",
        "memory_description: Per-table writer classification for legacy, analyzer-owned, support, and external-feed-derived tables. Generated by scripts/audit_db_write_surface.py; hand-classified for Phase 0.",
        "memory_tags: [audit, db, write-surface, phase-0, analyzer]",
        "---",
        "",
        "# DB Write-Surface Audit - Phase 0",
        "",
        f"**Generated:** {datetime.now(timezone.utc).isoformat()}",
        "**Reproduce:** `python3 scripts/audit_db_write_surface.py`",
        "",
        "## Summary",
        "",
        "This document starts from `scripts/brain_index.py deps --table <table>` for every table in the Phase 0 spec's §4.3 list. Writer classifications below are hand-reviewed after generation.",
        "",
    ]

    for table, klass in TABLES:
        lines.extend(
            [
                f"## `{table}` ({klass})",
                "",
                "```text",
                deps_for(repo, table),
                "```",
                "",
                "**Writers classified:** _populate by hand from the deps output_",
                "",
            ]
        )

    lines.extend(
        [
            "## External write paths",
            "",
            "### Supabase brain memory writes",
            "",
            "```text",
        ]
    )
    sites = supabase_memory_write_sites(repo)
    lines.extend(sites or ["(none found)"])
    lines.extend(
        [
            "```",
            "",
            "**Writers classified:** _populate by hand from the call sites above_",
            "",
            "### Per-run JSONL log emitters",
            "",
            "None today. Phase 1 adds runner-layer JSONL emitters.",
            "",
            "### Goldsky subgraph endpoints",
            "",
            "Read-only HTTP endpoints. No write surface.",
            "",
            "- `https://api.goldsky.com/api/public/project_cl6mb8i9h0003e201j6li0diw/subgraphs/activity-subgraph/0.0.4/gn`",
            "- `https://api.goldsky.com/api/public/project_cl6mb8i9h0003e201j6li0diw/subgraphs/orderbook-subgraph/0.0.1/gn`",
            "",
            "## Pattern B function list (locks Phase 0.5 §5.1)",
            "",
            "_populate by hand from `db_discovery.py` writer rows above_",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--out",
        default="docs/audits/2026-04-30-db-write-surface-audit.md",
        help="Markdown output path.",
    )
    args = parser.parse_args()

    repo = repo_root()
    out = Path(args.out)
    if not out.is_absolute():
        out = repo / out
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render_audit(repo) + "\n", encoding="utf-8")
    print(f"wrote {out.relative_to(repo) if out.is_relative_to(repo) else out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
