def _fav(d):
    """(side, price) of the market favorite at this checkpoint, or None if unavailable."""
    qm = d.get("q_market")
    if qm is None:
        return None
    side = "Up" if qm >= 0.5 else "Down"
    price = d.get("up_ask") if side == "Up" else d.get("down_ask")
    if price is None or not (0.0 < price < 1.0):
        return None
    return side, price


def _dog(d):
    f = _fav(d)
    if not f:
        return None
    dog = "Down" if f[0] == "Up" else "Up"
    price = d.get("up_ask") if dog == "Up" else d.get("down_ask")
    if price is None or not (0.0 < price < 1.0):
        return None
    return dog, price


def _struct_agrees(d):
    qs = d.get("q_struct")
    qm = d.get("q_market")
    if qs is None or qm is None:
        return None
    return (qm >= 0.5) == (qs >= 0.5)


# Each lane: cps={cp:featuredict} -> (checkpoint_used, side, price) or None to skip this window.
def _fav_at(cp):
    def f(cps):
        d = cps.get(cp)
        if not d:
            return None
        r = _fav(d)
        return (cp, r[0], r[1]) if r else None
    return f


def _fav_struct_at(cp):
    def f(cps):
        d = cps.get(cp)
        if not d or _struct_agrees(d) is not True:
            return None
        r = _fav(d)
        return (cp, r[0], r[1]) if r else None
    return f


def _fav_band_at(cp, lo, hi):
    def f(cps):
        d = cps.get(cp)
        if not d:
            return None
        r = _fav(d)
        if not r or not (lo <= r[1] <= hi):
            return None
        return (cp, r[0], r[1])
    return f


def _dog_structdis_at(cp):
    def f(cps):
        d = cps.get(cp)
        if not d or _struct_agrees(d) is not False:  # structural must DISAGREE with the market favorite
            return None
        r = _dog(d)
        return (cp, r[0], r[1]) if r else None
    return f


# --- terminal-volatility lanes (web research 2026-06-21): upset risk = terminal realized-vol SPIKE, NOT
# structural disagreement (which we proved can't call upsets). vol_ratio = realized/implied; <1 = calm
# (favorite reliable), high = realized running hot (turn-of-candle instability -> favorite may flip). ---
def _fav_calm_at(cp, vr_max=1.0):
    def f(cps):
        d = cps.get(cp)
        if not d:
            return None
        vr = d.get("vol_ratio")
        if vr is None or vr >= vr_max:   # only enter the favorite when realized vol is below implied (calm)
            return None
        r = _fav(d)
        return (cp, r[0], r[1]) if r else None
    return f


def _dog_hotvol_at(cp, vr_min=1.5):
    def f(cps):
        d = cps.get(cp)
        if not d:
            return None
        vr = d.get("vol_ratio")
        if vr is None or vr < vr_min:    # bet the underdog only when terminal vol is hot (upset window)
            return None
        r = _dog(d)
        return (cp, r[0], r[1]) if r else None
    return f


# --- v3 COMBINE C1 + quant (2026-06-21): the quant's fair value (q_trade) as a SELECTOR on top of the
# favorite, NEVER as an underdog picker (its proven -EV habit: underdog bets 17-33% WR, -25 to -50%).
# In-sample (n=44, context only): cheap favorites the quant AGREES with returned +13.5% vs +8.5% when it
# doubted. "Agrees" = q_trade is at least as confident in the favorite as the market (residual >= 0). ---
def _fav_quant_resid(d):
    """(side, price, fav_residual) for the favorite, where fav_residual >0 = quant more confident than
    the market in the favorite. None if q_market/q_trade/price unavailable."""
    qm, qt = d.get("q_market"), d.get("q_trade")
    if qm is None or qt is None:
        return None
    r = _fav(d)
    if not r:
        return None
    fav_resid = (qt - qm) if qm >= 0.5 else (qm - qt)
    return r[0], r[1], fav_resid


def _fav_qagree_at(cp, lo=0.0, hi=0.92):
    def f(cps):
        d = cps.get(cp)
        if not d:
            return None
        fr = _fav_quant_resid(d)
        if not fr or fr[2] < 0 or not (lo <= fr[1] <= hi):   # quant must agree; skip fee-eaten near-certain
            return None
        return (cp, fr[0], fr[1])
    return f


# --- v4 (2026-06-21) — Family A (favorite × quant-component agreement) + Family B (underdog) lanes.
# A quant signal (q_trade / q_struct / q_mc, each a P(Up)) AGREES with the favorite if it points the same
# direction as q_market. See the design spec 2026-06-21-crypto5m-quant-lane-expansion-design.md. ---
_SIGNALS = ("q_trade", "q_struct", "q_mc")


def _sig_agrees_fav(d, key):
    s, qm = d.get(key), d.get("q_market")
    if s is None or qm is None:
        return None
    return (qm >= 0.5) == (s >= 0.5)


def _fav_sig_agree_at(cp, key, lo=0.0, hi=0.92):
    def f(cps):
        d = cps.get(cp)
        if not d or _sig_agrees_fav(d, key) is not True:
            return None
        r = _fav(d)
        return (cp, r[0], r[1]) if (r and lo <= r[1] <= hi) else None
    return f


def _fav_consensus_at(cp, lo=0.0, hi=0.92):
    def f(cps):
        d = cps.get(cp)
        if not d:
            return None
        ags = [_sig_agrees_fav(d, k) for k in _SIGNALS]
        if any(a is None for a in ags) or not all(ags):   # every quant component must agree
            return None
        r = _fav(d)
        return (cp, r[0], r[1]) if (r and lo <= r[1] <= hi) else None
    return f


def _fav_strong_at(cp, thr=0.03, hi=0.92):
    def f(cps):
        d = cps.get(cp)
        if not d:
            return None
        fr = _fav_quant_resid(d)
        return (cp, fr[0], fr[1]) if (fr and fr[2] >= thr and fr[1] <= hi) else None
    return f


def _fav_alldisagree_at(cp):
    def f(cps):
        d = cps.get(cp)
        if not d:
            return None
        ags = [_sig_agrees_fav(d, k) for k in _SIGNALS]
        if any(a is None for a in ags) or any(ags):        # ALL components disagree with the favorite
            return None
        r = _fav(d)
        return (cp, r[0], r[1]) if r else None
    return f


def _dog_weakfav_at(cp, fav_lo=0.50, fav_hi=0.65):
    def f(cps):
        d = cps.get(cp)
        if not d:
            return None
        fav = _fav(d)
