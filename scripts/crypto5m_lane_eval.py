def load_windows(conn):
    """condition_id -> {cp: feat, '_ts': {cp: decision_ts}, '_win': 'Up'/'Down'}."""
    sett = {r[0]: r[1] for r in conn.execute(
        "SELECT condition_id, winning_outcome FROM crypto5m_quant_settlements")}
    win = {}
    for cid, cp, ts, mj in conn.execute(
            "SELECT condition_id, checkpoint, decision_ts, matrix_json FROM crypto5m_quant_matrix"):
        w = sett.get(cid)
        if w not in ("Up", "Down"):
            continue
        m = json.loads(mj)
        qc = m.get("q_components", {})
        panel = m.get("panel", {})
        rec = win.setdefault(cid, {"_ts": {}, "_win": w})
        rec[cp] = {"q_market": m.get("q_market"), "up_ask": m.get("up_best_ask"),
                   "down_ask": m.get("down_best_ask"), "q_struct": qc.get("q_struct_realized"),
                   "q_mc": qc.get("q_mc"), "vol_ratio": panel.get("vol_ratio"),
                   "vol_regime": panel.get("vol_regime"), "q_trade": m.get("q_trade"),
                   "up_ofi": m.get("up_order_flow_imbalance"), "down_ofi": m.get("down_order_flow_imbalance")}
        rec["_ts"][cp] = ts
    return win


def _roi_net(price, won):
    """Per-$1-staked net ROI: win -> (1/price - 1), lose -> -1; minus the entry taker fee rate*(1-price)."""
    return (((1.0 / price) - 1.0) if won else -1.0) - TAKER_FEE_RATE * (1.0 - price)


def _c1_ref(rec, cp):
    """Plain-favorite (C1) pick at checkpoint cp: (side, price, roi_net) — the Family-A benchmark. None if NA."""
    d = rec.get(cp)
    if not d:
        return None
    r = _fav(d)
    if not r:
        return None
    return r[0], r[1], _roi_net(r[1], 1 if rec["_win"] == r[0] else 0)


def _bucket(ts):
    return "oos" if ts >= FREEZE_TS else "in_sample"


def evaluate_lane(name, fn, windows):
    """For each sample bucket: the lane's KEPT picks (cid, roi, price, won) and — for Family A — the C1
    reference on windows the lane SKIPPED (the self-review's load-bearing kept-vs-skipped comparison)."""
    fam, cp, _desc = LANE_META.get(name, ("A", 240, ""))
    kept = {"in_sample": [], "oos": []}
    skipped = {"in_sample": [], "oos": []}
    for cid, rec in windows.items():
        pick = fn(rec)
        if pick:
            pc, side, price = pick
            won = 1 if rec["_win"] == side else 0
            kept[_bucket(rec["_ts"].get(pc, 0))].append((cid, _roi_net(price, won), price, won))
        elif fam == "A":
            ref = _c1_ref(rec, cp)
            if ref:
                won = 1 if rec["_win"] == ref[0] else 0
                skipped[_bucket(rec["_ts"].get(cp, 0))].append((cid, ref[2], ref[1], won))
    return fam, cp, kept, skipped


def _summary(picks):
    if not picks:
        return {"n": 0}
    n = len(picks)
    return {"n": n, "wins": sum(p[3] for p in picks), "win_pct": 100.0 * sum(p[3] for p in picks) / n,
            "avg_price": sum(p[2] for p in picks) / n, "net_roi_pct": 100.0 * sum(p[1] for p in picks) / n}


def _by_window(picks):
    d = defaultdict(list)
    for cid, roi, _p, _w in picks:
        d[cid].append(roi)
    return d


# _boot_means / _pctile imported from window_bootstrap (see top-of-file import).


def lane_significance(fam, kept_oos, skipped_oos, rng):
    """OOS verdict. Family A: the kept-vs-skipped GAP (>0 = the selector beats taking every favorite).
    Family B / control: net ROI vs 0. Min-n gate first; one-sided bootstrap p + 95% CI."""
    ksum = _summary(kept_oos)
    res = {"net_roi_pct": ksum.get("net_roi_pct"), "win_pct": ksum.get("win_pct"), "n": ksum["n"],
           "pval": None, "gap_pct": None, "gap_ci_lo": None, "gap_ci_hi": None,
           "skipped_n": 0, "skipped_roi_pct": None}
    if ksum["n"] < MIN_N_OOS:
        res["status"] = "accruing"
        return res
    kbw = _by_window(kept_oos)
    if fam == "A":
        ssum = _summary(skipped_oos)
        res["skipped_n"], res["skipped_roi_pct"] = ssum.get("n", 0), ssum.get("net_roi_pct")
        sbw = _by_window(skipped_oos)
        if not sbw:                                  # lane took EVERY favorite window -> ~= C1, nothing to test
            res["status"] = "no_complement"
            return res
        km, sm = _boot_means(kbw, rng), _boot_means(sbw, rng)
        diffs = sorted(km[i] - sm[i] for i in range(min(len(km), len(sm))))
        res["gap_pct"] = 100.0 * sum(diffs) / len(diffs)
        res["gap_ci_lo"], res["gap_ci_hi"] = 100.0 * _pctile(diffs, 0.025), 100.0 * _pctile(diffs, 0.975)
        res["pval"] = sum(1 for d in diffs if d <= 0) / len(diffs)
    else:
        means = _boot_means(kbw, rng)
        res["gap_pct"] = ksum["net_roi_pct"]         # vs benchmark 0
        res["gap_ci_lo"], res["gap_ci_hi"] = 100.0 * _pctile(means, 0.025), 100.0 * _pctile(means, 0.975)
        res["pval"] = sum(1 for m in means if m <= 0) / len(means)
    return res


def bh_fdr(pairs, q=FDR_Q):
    """Benjamini-Hochberg survivors. pairs=[(key,p)]. APPROXIMATE: lanes are non-independent nested subsets,
    so this is a p-hacking guard, not an exact FDR — the per-lane gap CI is the more robust signal."""
    valid = sorted(((k, p) for k, p in pairs if p is not None), key=lambda x: x[1])
    m = len(valid)
    rank = 0
    for i, (_k, p) in enumerate(valid, 1):
        if p <= (i / m) * q:
            rank = i
    return {k for i, (k, _p) in enumerate(valid, 1) if i <= rank}


def evaluate_all(windows):
    rng = random.Random(BOOT_SEED)
    lanes = {}
    for name, fn in LANES.items():
        fam, cp, kept, skipped = evaluate_lane(name, fn, windows)
        lanes[name] = {"family": fam, "cp": cp, "benchmark": ("C1" if fam == "A" else "0"),
                       "desc": LANE_META.get(name, (None, None, ""))[2],
                       "in_sample": _summary(kept["in_sample"]),
                       "oos": lane_significance(fam, kept["oos"], skipped["oos"], rng)}
    survive = bh_fdr([(n, d["oos"].get("pval")) for n, d in lanes.items()])
    for name, d in lanes.items():
        o = d["oos"]
        o["fdr_pass"] = name in survive
        if o.get("status") in ("accruing", "no_complement"):
            continue
        o["status"] = "promising" if ((o.get("gap_ci_lo") or -1) > 0 and o["fdr_pass"]) else "no_edge"
    return lanes


