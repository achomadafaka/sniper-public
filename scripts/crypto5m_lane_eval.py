"""Crypto-5m candidate-lane forward harness (pre-registered, READ-ONLY, NO ORDERS).

The quant-shadow matrix (`crypto5m_quant_matrix`) is a COMPLETE per-window feature log: for every
settled BTC-updown-5m window it stores q_market, q_struct, both-book asks, OFI, vol regime, etc. at
checkpoints 120/180/240/270s. A candidate "lane" is therefore just a pure function over that log, so we
can score any number of lanes both retrospectively AND forward — for free, no new live process.

DISCIPLINE (mirrors btc5m-forward-paper-v0): the lane set + FREEZE_TS below are FROZEN. Results are split
into IN-SAMPLE (windows decided before FREEZE_TS — these inspired the lanes, so they carry overfitting
risk and are reported only for context) and OOS (windows decided at/after FREEZE_TS — the real test).
Only OOS numbers may ever be cited as evidence. New ideas = bump LANE_VERSION + a new FREEZE_TS, never
silently edit a frozen lane. Read-only: never writes the frozen shadow/forward DBs; results go to a
separate lane_eval DB.

Lanes were generated by an in-sample exploratory pass (n=25, 2026-06-21) showing: the favorite is broadly
underpriced at the 240s checkpoint (lead-lag agreement 0.697 — book lags the realized BTC move); near-
certain 0.95+ favorites are ~breakeven gross (fee-eaten); 120s entry is cheaper at comparable gross EV;
and the structural model does NOT separate upsets (underdog-on-disagreement lost). The lanes test each of
those hypotheses out-of-sample.
"""
