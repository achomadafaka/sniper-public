def ensure_result_schema(conn):
    conn.execute("""CREATE TABLE IF NOT EXISTS crypto5m_lane_results (
        lane_version TEXT, lane TEXT, sample TEXT, n INTEGER, wins INTEGER,
        win_pct REAL, avg_price REAL, gross_roi_pct REAL, fee_roi_pct REAL,
        freeze_ts INTEGER, updated_ts INTEGER,
        PRIMARY KEY (lane_version, lane, sample))""")
    have = {r[1] for r in conn.execute("PRAGMA table_info(crypto5m_lane_results)")}
    for col, typ in _EXTRA_COLS:
        if col not in have:
            conn.execute(f"ALTER TABLE crypto5m_lane_results ADD COLUMN {col} {typ}")
    conn.commit()


