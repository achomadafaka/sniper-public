"""Persistence for the Live Wallet Signals board: `wallet_signal_profiles` (an explainable,
analyzer-backed signal PROFILE per rostered wallet — NOT a grade/score) and `live_positions` (current
open positions per profiled wallet, refreshed by the poller). Both are display/intelligence surfaces —
no analyzer-verdict mutation. Lazy-ensure accessor pattern. (Table was `wallet_grades`; renamed to
drop the overclaiming 'grade' framing — it's research-attention triage, not certification.)"""
from __future__ import annotations

import json
import sqlite3
import time


def ensure_wallet_signals_tables(conn: sqlite3.Connection) -> None:
    from db import with_db_init_lock
    with with_db_init_lock(conn):
        conn.executescript(
            """
            CREATE TABLE IF NOT EXISTS wallet_signal_profiles (
                wallet TEXT PRIMARY KEY,
                archetype TEXT NOT NULL DEFAULT 'unknown',
                intent TEXT,
                archetype_confidence TEXT NOT NULL DEFAULT 'low',
                copy_policy TEXT NOT NULL DEFAULT 'study_only',
                directional_profile INTEGER NOT NULL DEFAULT 0,
                in_sample_edge_read TEXT NOT NULL DEFAULT 'profitable_unproven',
                edge_read_strength TEXT NOT NULL DEFAULT 'low',
                edge_domains TEXT NOT NULL DEFAULT '[]',
                primary_tag TEXT,
                q75_usdc REAL NOT NULL DEFAULT 0,
                description TEXT NOT NULL DEFAULT '',
                profiled_ts INTEGER NOT NULL DEFAULT 0,
                analyzed_ts INTEGER NOT NULL DEFAULT 0
            );
            CREATE TABLE IF NOT EXISTS live_positions (
                wallet TEXT NOT NULL,
                condition_id TEXT NOT NULL,
                outcome_index INTEGER NOT NULL,
                outcome TEXT NOT NULL DEFAULT '',
                title TEXT NOT NULL DEFAULT '',
                event_slug TEXT NOT NULL DEFAULT '',
                league TEXT,
                size REAL NOT NULL DEFAULT 0,
                avg_price REAL NOT NULL DEFAULT 0,
                cur_price REAL NOT NULL DEFAULT 0,
                current_value REAL NOT NULL DEFAULT 0,
                cash_pnl REAL NOT NULL DEFAULT 0,
                is_open INTEGER NOT NULL DEFAULT 1,
                first_seen_ts INTEGER NOT NULL DEFAULT 0,
                synced_ts INTEGER NOT NULL DEFAULT 0,
                PRIMARY KEY (wallet, condition_id, outcome_index)
            );
            CREATE INDEX IF NOT EXISTS idx_live_positions_open ON live_positions(is_open, wallet);
            """
        )
        _migrate_legacy_wallet_grades(conn)


def _migrate_legacy_wallet_grades(conn: sqlite3.Connection) -> int:
    """One-time, non-destructive: if a pre-rename `wallet_grades` table exists and the new
    `wallet_signal_profiles` is still empty, copy rows across with the column-rename mapping
    (copyable/copyable_archetype->directional_profile, edge_verdict->in_sample_edge_read,
    edge_confidence->edge_read_strength, graded_ts->profiled_ts) so a deployment that predates the
    rename doesn't lose board visibility. The analyzer gate (grade_roster prune) reconciles any
    non-analyzer-backed rows on its next run. Best-effort — never breaks startup. Returns # copied."""
    import logging
    try:
        if not conn.execute("SELECT 1 FROM sqlite_master WHERE type='table' AND name='wallet_grades'").fetchone():
            return 0
        if conn.execute("SELECT 1 FROM wallet_signal_profiles LIMIT 1").fetchone():
            return 0  # already populated (regenerated by the grader) — leave the legacy table alone
        cols = {r[1] for r in conn.execute("PRAGMA table_info(wallet_grades)")}
        if "wallet" not in cols:
            return 0

        def keep(col: str, default_sql: str) -> str:  # NOT NULL target: COALESCE present col, else literal
            return f"COALESCE({col}, {default_sql})" if col in cols else default_sql

        def first(aliases: tuple, default_sql: str) -> str:
            for a in aliases:
                if a in cols:
                    return f"COALESCE({a}, {default_sql})"
            return default_sql

        sel = ", ".join([
            "wallet",
            keep("archetype", "'unknown'"),
            "intent" if "intent" in cols else "NULL",
            keep("archetype_confidence", "'low'"),
            keep("copy_policy", "'study_only'"),
            first(("copyable", "copyable_archetype", "directional_profile"), "0"),
            first(("edge_verdict", "in_sample_edge_read"), "'profitable_unproven'"),
            first(("edge_confidence", "edge_read_strength"), "'low'"),
            keep("edge_domains", "'[]'"),
            "primary_tag" if "primary_tag" in cols else "NULL",
            keep("q75_usdc", "0"),
            keep("description", "''"),
            first(("graded_ts", "profiled_ts"), "0"),
            keep("analyzed_ts", "0"),
        ])
        n = conn.execute(
            f"""INSERT OR IGNORE INTO wallet_signal_profiles
                  (wallet, archetype, intent, archetype_confidence, copy_policy, directional_profile,
                   in_sample_edge_read, edge_read_strength, edge_domains, primary_tag, q75_usdc,
                   description, profiled_ts, analyzed_ts)
                SELECT {sel} FROM wallet_grades""").rowcount
        conn.commit()
        if n:
            logging.getLogger(__name__).info(
                "migrated %d legacy wallet_grades rows -> wallet_signal_profiles", n)
        return n or 0
    except Exception:  # noqa: BLE001 — migration is best-effort; never block table creation
        logging.getLogger(__name__).exception("legacy wallet_grades migration skipped")
        return 0


def upsert_profile(conn: sqlite3.Connection, g: dict, *, now_ts: int | None = None) -> None:
    ensure_wallet_signals_tables(conn)
    ts = now_ts if now_ts is not None else int(time.time())
    conn.execute(
        """INSERT INTO wallet_signal_profiles (wallet, archetype, intent, archetype_confidence,
             copy_policy, directional_profile, in_sample_edge_read, edge_read_strength, edge_domains,
             primary_tag, q75_usdc, description, profiled_ts, analyzed_ts)
           VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?)
           ON CONFLICT(wallet) DO UPDATE SET archetype=excluded.archetype, intent=excluded.intent,
             archetype_confidence=excluded.archetype_confidence, copy_policy=excluded.copy_policy,
             directional_profile=excluded.directional_profile,
             in_sample_edge_read=excluded.in_sample_edge_read,
             edge_read_strength=excluded.edge_read_strength, edge_domains=excluded.edge_domains,
             primary_tag=excluded.primary_tag, q75_usdc=excluded.q75_usdc,
             description=excluded.description, profiled_ts=excluded.profiled_ts,
             analyzed_ts=excluded.analyzed_ts""",
        (g["wallet"].lower(), g.get("archetype") or "unknown", g.get("intent"),
         g.get("archetype_confidence") or "low", g.get("copy_policy") or "study_only",
         1 if g.get("directional_profile") else 0, g.get("in_sample_edge_read") or "profitable_unproven",
         g.get("edge_read_strength") or "low", json.dumps(g.get("edge_domains") or []),
         g.get("primary_tag"), float(g.get("q75_usdc") or 0.0), g.get("description") or "",
         ts, int(g.get("analyzed_ts") or 0)),
    )
    conn.commit()


def _profile_row(row: sqlite3.Row) -> dict:
    d = dict(row)
    d["directional_profile"] = bool(d.get("directional_profile"))
    try:
        d["edge_domains"] = json.loads(d.get("edge_domains") or "[]")
    except Exception:  # noqa: BLE001
        d["edge_domains"] = []
    return d


def all_profiles(conn: sqlite3.Connection) -> dict:
    """wallet -> signal-profile dict."""
    ensure_wallet_signals_tables(conn)
    conn.row_factory = sqlite3.Row
    return {r["wallet"]: _profile_row(r) for r in conn.execute("SELECT * FROM wallet_signal_profiles")}


def upsert_live_position(conn: sqlite3.Connection, row: dict, *, now_ts: int | None = None) -> None:
    ensure_wallet_signals_tables(conn)
    ts = now_ts if now_ts is not None else int(time.time())
    conn.execute(
        """INSERT INTO live_positions (wallet, condition_id, outcome_index, outcome, title,
             event_slug, league, size, avg_price, cur_price, current_value, cash_pnl, is_open,
             first_seen_ts, synced_ts)
           VALUES (?,?,?,?,?,?,?,?,?,?,?,?,1,?,?)
           ON CONFLICT(wallet, condition_id, outcome_index) DO UPDATE SET outcome=excluded.outcome,
             title=excluded.title, event_slug=excluded.event_slug, league=excluded.league,
             size=excluded.size, avg_price=excluded.avg_price, cur_price=excluded.cur_price,
             current_value=excluded.current_value, cash_pnl=excluded.cash_pnl, is_open=1,
             synced_ts=excluded.synced_ts""",
        (row["wallet"].lower(), row["condition_id"], int(row["outcome_index"]),
         row.get("outcome") or "", row.get("title") or "", row.get("event_slug") or "",
         row.get("league"), float(row.get("size") or 0.0), float(row.get("avg_price") or 0.0),
         float(row.get("cur_price") or 0.0), float(row.get("current_value") or 0.0),
         float(row.get("cash_pnl") or 0.0), ts, ts),
    )
    conn.commit()


def mark_closed(conn: sqlite3.Connection, wallet: str, open_keys: set) -> None:
    """Flip is_open=0 for the wallet's stored positions NOT in the current open set.
    open_keys = {(condition_id, outcome_index)}."""
    ensure_wallet_signals_tables(conn)
    conn.row_factory = sqlite3.Row
    for r in conn.execute("SELECT condition_id, outcome_index FROM live_positions WHERE wallet=? AND is_open=1",
                          (wallet.lower(),)):
        if (r["condition_id"], r["outcome_index"]) not in open_keys:
            conn.execute("UPDATE live_positions SET is_open=0 WHERE wallet=? AND condition_id=? AND outcome_index=?",
                         (wallet.lower(), r["condition_id"], r["outcome_index"]))
    conn.commit()


def open_positions(conn: sqlite3.Connection) -> list:
    ensure_wallet_signals_tables(conn)
    conn.row_factory = sqlite3.Row
    # Defensive cur_price>0 filter (CODEX P2): a stale RESOLVED row may already sit in live_positions
    # with cur_price=0, is_open=1 (persisted before the redeemable poller fix, or a wallet not re-polled).
    # A worthless resolved bet is not a live signal — never surface it on the board or to enroll.
    return [dict(r) for r in conn.execute(
        "SELECT * FROM live_positions WHERE is_open=1 AND COALESCE(cur_price,0) > 0")]


def prune_profiles(conn: sqlite3.Connection, keep_wallets) -> int:
    """Delete signal profiles (and their live_positions) for any wallet NOT in keep_wallets — used to
    purge profiles that bypassed the deep analyzer (a profile must be analyzer-backed). Returns # pruned."""
    ensure_wallet_signals_tables(conn)
    keep = {str(w).lower() for w in (keep_wallets or [])}
    have = [r[0] for r in conn.execute("SELECT wallet FROM wallet_signal_profiles")]
    drop = [w for w in have if w.lower() not in keep]
    for w in drop:
        conn.execute("DELETE FROM wallet_signal_profiles WHERE wallet=?", (w,))
        conn.execute("DELETE FROM live_positions WHERE wallet=?", (w,))
    conn.commit()
    return len(drop)
